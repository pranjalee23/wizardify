// Cuts the phone versions of the page backgrounds. A background is a fixed height and as wide as the
// screen, cropped like object-fit: cover, so a phone only ever sees a strip from its middle. Phones get
// just that strip, at full sharpness, as a much smaller file. Writes public/images/*-phone.webp, and
// lib/phone-crops.ts for components/LitImage.
// Usage: node scripts/backgrounds/phone.mjs   (needs Google Chrome installed)
import { chromium } from 'playwright'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, extname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '../..')

// Shown to screens up to 700 px wide; must match PHONE_MEDIA in components/LitImage.module.css
const media = '(max-width: 700px)'

// Each strip is what screens up to 700 px wide show of the picture (measured on every page that uses
// it), as shares of its width, plus 3% of its width either side. Measure again if a page changes how
// tall its background is or where it's cropped (--ox).
const crops = [
  { src: 'hero-room.webp', from: 0.427, to: 0.75 }, // the home page hero
  { src: 'room-lit.webp', from: 0.273, to: 0.727 }, // NightSky's candlelit room
  { src: 'sky-study.jpg', from: 0.273, to: 0.727 }, // NightSky's study
  { src: 'castle-night.webp', from: 0.396, to: 0.682 }, // CastleNight
]

const types = { '.webp': 'image/webp', '.jpg': 'image/jpeg', '.png': 'image/png' }
const browser = await chromium.launch({ channel: 'chrome' })
const page = await browser.newPage()
const entries = []
for (const c of crops) {
  const file = join(root, 'public/images', c.src)
  const data = `data:${types[extname(c.src)]};base64,${readFileSync(file).toString('base64')}`
  const out = await page.evaluate(async ({ data, from, to }) => {
    const img = new Image()
    img.src = data
    await img.decode()
    const x = Math.floor(img.naturalWidth * from)
    const w = Math.ceil(img.naturalWidth * to) - x
    const canvas = document.createElement('canvas')
    canvas.width = w
    canvas.height = img.naturalHeight
    canvas.getContext('2d').drawImage(img, x, 0, w, img.naturalHeight, 0, 0, w, img.naturalHeight)
    return { url: canvas.toDataURL('image/webp', 0.86), x, w, W: img.naturalWidth }
  }, { data, ...c })
  const name = c.src.replace(/\.\w+$/, '-phone.webp')
  const buf = Buffer.from(out.url.split(',')[1], 'base64')
  writeFileSync(join(root, 'public/images', name), buf)
  entries.push(`  '/images/${c.src}': { src: '/images/${name}', x: ${+(out.x / out.W).toFixed(5)}, w: ${+(out.w / out.W).toFixed(5)} },`)
  console.log(`${name}  ${Math.round(buf.length / 1024)} KB (the full picture is ${Math.round(readFileSync(file).length / 1024)} KB)`)
}
await browser.close()

writeFileSync(
  join(root, 'lib/phone-crops.ts'),
  `// Generated by scripts/backgrounds/phone.mjs; don't edit by hand. The strip of each background that
// phones see, cut out as its own smaller picture: where it starts (x) and how wide it is (w), as
// shares of the full picture's width.
export const PHONE_MEDIA = '${media}'

export type PhoneCrop = { src: string; x: number; w: number }

export const phoneCrops: Record<string, PhoneCrop> = {
${entries.join('\n')}
}
`,
)
