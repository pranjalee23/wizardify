// Builds the rigs that bring the site's decorative owls to life (components/LivingOwl), and
// lib/owls.ts, which says where each owl's parts are. The home hero's owl is built with the rest of
// its scene, by scripts/hero/build.mjs.
// Usage: node scripts/owl/build.mjs   (needs Google Chrome installed)
import { chromium } from 'playwright'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '../..')

// In each picture's own pixels. `look` is how far the face slides when the owl looks aside; `wing`
// says which way the wing lifts (-1 for a wing on the owl's left, as seen) and how far.
const owls = {
  // Gallery and FAQ: the owl standing on books
  galleryOwl: {
    src: 'deco-gallery-right.png',
    size: [641, 742],
    neck: [150, 235],
    headPivot: [303, 200],
    face: [303, 90, 110, 75],
    eyes: [[262, 71, 17, 14], [346, 71, 16, 14]],
    feetY: 495,
    look: 16,
    wing: {
      turn: -1,
      amp: 1,
      pivot: [205, 190],
      outline: [
        [150, 185], [200, 168], [250, 170], [262, 210], [262, 280], [252, 340], [238, 400], [222, 450],
        [200, 500], [170, 540], [130, 545], [95, 520], [88, 440], [100, 340], [115, 260], [128, 210],
      ],
    },
  },
  // The house pages: the owl on a branch with one wing raised
  houseOwl: {
    src: 'deco-house.png',
    size: [694, 727],
    neck: [140, 215],
    headPivot: [490, 190],
    face: [490, 85, 95, 75],
    eyes: [[446, 63, 10, 13], [525, 63, 20, 14]],
    feetY: 520,
    look: 14,
    wing: {
      turn: -1,
      amp: 1.8,
      pivot: [340, 190],
      outline: [
        [320, 112], [264, 100], [208, 120], [160, 160], [112, 216], [64, 288], [16, 360], [0, 408],
        [40, 496], [80, 504], [128, 480], [184, 432], [216, 400], [264, 352], [304, 264], [336, 200],
        [352, 144],
      ],
    },
  },
}

const browser = await chromium.launch({ channel: 'chrome' })
const page = await browser.newPage()
await page.addScriptTag({ content: readFileSync(join(root, 'scripts/owl/rig.js'), 'utf8') })

const entries = []
for (const [name, o] of Object.entries(owls)) {
  const url = await page.evaluate(
    (o) => window.buildOwlRig({ origin: [0, 0], size: o.size, neck: o.neck, wing: o.wing.outline, face: o.face }),
    o,
  )
  const rigName = o.src.replace(/\.png$/, '-rig.png')
  writeFileSync(join(root, 'public/images', rigName), Buffer.from(url.split(',')[1], 'base64'))
  entries.push(`export const ${name}: OwlRig = {
  src: '/images/${o.src}',
  rig: '/images/${rigName}',
  size: [${o.size.join(', ')}],
  headPivot: [${o.headPivot.join(', ')}],
  wingPivot: [${o.wing.pivot.join(', ')}],
  faceCentre: [${o.face.slice(0, 2).join(', ')}],
  feetY: ${o.feetY},
  eyes: [
${o.eyes.map((e) => `    [${e.join(', ')}],`).join('\n')}
  ],
  look: ${o.look},
  wingTurn: ${o.wing.turn},
  wingAmp: ${o.wing.amp},
}`)
  console.log(rigName)
}
await browser.close()

writeFileSync(
  join(root, 'lib/owls.ts'),
  `// Generated by scripts/owl/build.mjs; don't edit by hand. The site's decorative owls, for
// components/LivingOwl. Positions are in each picture's own pixels.
import type { OwlRig } from '@/components/LivingOwl'

${entries.join('\n\n')}
`,
)
